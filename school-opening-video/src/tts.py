import certifi, os, sys, asyncio, json, subprocess
certifi.where = lambda: "/root/.ccr/ca-bundle.crt"
import edge_tts
VOICE = sys.argv[1] if len(sys.argv)>1 else "ar-SA-HamedNeural"
S = [
 "حين يكونُ العلمُ رسالة، ويكونُ التعليمُ أساساً لبناءِ الأجيال... تبدأُ الحكاياتُ العظيمة، وتُفتَحُ أبوابُ المستقبل.",
 "فالعلمُ نورٌ يهدي العقول، والمعرفةُ طريقٌ يصنعُ الطموحات، والتربيةُ رسالةٌ تبني الإنسان، وتمنحُه القدرةَ على صناعةِ الغد.",
 "ومن هنا، من هذا الصرحِ التعليمي، تنطلقُ خطواتُ الطموح، وتُرسَمُ ملامحُ النجاح، وتُغرَسُ في نفوسِ أبنائِنا قيمُ الاجتهادِ والانضباطِ والإبداع.",
 "وبكلِّ فخرٍ واعتزاز، نُعلنُ افتتاحَ مدرسةِ ثانويةِ حيِّ النِّفطِ للبنين... صرحاً للعلم، ومنارةً للمعرفة، ومساحةً للأملِ والطموح.",
 "هنا تُصقَلُ المواهب، وتُنمّى القدرات، وتُفتَحُ أمامَ الأجيالِ آفاقٌ أوسعُ للتعلُّمِ والإنجاز. هنا تبدأُ رحلةٌ جديدة، عنوانُها الطموح، وغايتُها النجاح، وأساسُها العلمُ والمعرفة.",
 "مدرسةُ ثانويةِ حيِّ النِّفطِ للبنين... حيثُ يُشرقُ العلم، ويُصنَعُ الأمل، ويبدأُ المستقبل.",
]
async def main():
    for i,t in enumerate(S):
        c = edge_tts.Communicate(t, VOICE, rate="+4%", pitch="-6Hz", proxy=os.environ.get("HTTPS_PROXY"))
        await c.save(f"vo/s{i+1}.mp3")
asyncio.run(main())
for i in range(6):
    d = subprocess.check_output(["ffprobe","-v","quiet","-show_entries","format=duration","-of","csv=p=0",f"vo/s{i+1}.mp3"]).decode().strip()
    print(i+1, d)
